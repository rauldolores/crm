-- Bandeja compartida del equipo: los correos que los clientes mandan a la
-- dirección de la organización (hola@…), visibles para todo el equipo y
-- contestables desde el CRM. Ver .product/requirements/REQ-2026-001.md.

-- Dónde recibe la organización. Guarda el secreto del aviso de Resend y,
-- si hace falta, una clave para leer el correo recibido: como
-- email_settings, sin políticas y solo para service_role.
create table crm.inbox_settings (
    organization_id uuid not null primary key,
    provider text not null default 'resend'
        constraint inbox_settings_provider_check check (provider in ('resend')),
    -- La dirección de la bandeja. También va como Reply-To en todo correo
    -- que sale del CRM, para que las respuestas lleguen aquí.
    inbox_email text not null,
    -- Secreto con el que Resend firma cada aviso (whsec_…).
    webhook_secret text,
    -- Clave para leer el correo recibido. Nula: se usa la del correo
    -- saliente, que basta si es de acceso completo.
    api_key text,
    active boolean not null default true,
    last_received_at timestamp with time zone,
    last_error text,
    last_error_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);

-- Una conversación con alguien de fuera. El canal es un campo, no una
-- tabla aparte: WhatsApp entrará a esta misma bandeja.
create table crm.conversations (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    channel text not null default 'email'
        constraint conversations_channel_check check (channel in ('email')),
    -- Nulo: nadie con esa dirección en los contactos («Sin contacto»).
    contact_id bigint references crm.contacts(id) on delete set null,
    -- La dirección del otro lado: con ella se enlaza a un contacto después.
    counterpart text not null,
    counterpart_name text,
    subject text,
    -- pending: espera respuesta del equipo; answered: ya se le contestó;
    -- closed: no hace falta hacer nada.
    status text not null default 'pending'
        constraint conversations_status_check
        check (status in ('pending', 'answered', 'closed')),
    unread boolean not null default true,
    -- Quién la atiende: el responsable del contacto. Nulo = pila compartida.
    sales_id bigint references crm.sales(id) on delete set null,
    -- Todo lo que llegó fueron respuestas automáticas (fuera de oficina,
    -- rebotes): se guarda, pero no pide atención.
    automatic boolean not null default false,
    last_message_at timestamp with time zone not null default now(),
    last_message_preview text,
    created_at timestamp with time zone not null default now()
);

create index conversations_organization_status_idx
    on crm.conversations (organization_id, status, last_message_at desc);
create index conversations_contact_id_idx on crm.conversations (contact_id);

create table crm.conversation_messages (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    conversation_id bigint not null
        references crm.conversations(id) on delete cascade,
    direction text not null
        constraint conversation_messages_direction_check
        check (direction in ('in', 'out')),
    from_email text not null,
    from_name text,
    to_emails text[] not null default '{}',
    cc_emails text[] not null default '{}',
    subject text,
    body_text text,
    -- Cabeceras de hilo: con ellas una respuesta encuentra su conversación.
    message_id text,
    in_reply_to text,
    reference_ids text[] not null default '{}',
    -- Id del correo en el proveedor: un aviso repetido no lo duplica.
    provider_id text,
    -- Quién del equipo lo escribió (solo salientes).
    sales_id bigint references crm.sales(id) on delete set null,
    automatic boolean not null default false,
    -- Nombre, tipo y tamaño de cada adjunto; el contenido sigue en el proveedor.
    attachments jsonb not null default '[]'::jsonb,
    sent_at timestamp with time zone not null default now(),
    created_at timestamp with time zone not null default now()
);

create unique index conversation_messages_message_id_uk
    on crm.conversation_messages (organization_id, message_id);
create unique index conversation_messages_provider_id_uk
    on crm.conversation_messages (organization_id, provider_id);
create index conversation_messages_conversation_id_idx
    on crm.conversation_messages (conversation_id, sent_at);

-- Lectura para la organización; nadie escribe por PostgREST. Todo cambio
-- pasa por /api/bandeja, que comprueba que el contacto y el responsable
-- sean de la misma organización.
alter table crm.inbox_settings enable row level security;
alter table crm.conversations enable row level security;
alter table crm.conversation_messages enable row level security;

create policy "Conversations are scoped to the organization" on crm.conversations
    for select to authenticated
    using (organization_id = crm.current_organization_id());
create policy "Conversation messages are scoped to the organization" on crm.conversation_messages
    for select to authenticated
    using (organization_id = crm.current_organization_id());

revoke all on table crm.inbox_settings from anon, authenticated;
grant select, insert, update, delete on table crm.inbox_settings to service_role;
revoke all on table crm.conversations from anon, authenticated;
revoke all on table crm.conversation_messages from anon, authenticated;
grant select on table crm.conversations to authenticated, service_role;
grant select on table crm.conversation_messages to authenticated, service_role;
grant all on table crm.conversations to service_role;
grant all on table crm.conversation_messages to service_role;

-- «RE: RV: Fwd: Hola» y «hola» son el mismo hilo.
create or replace function crm.asunto_de_hilo(asunto text)
returns text
language sql
immutable
set search_path = ''
as $$
  select btrim(regexp_replace(
    lower(coalesce(asunto, '')),
    '^(\s*(re|rv|fw|fwd|res|enc)\s*(\[\d+\])?\s*:\s*)+',
    ''
  ));
$$;

-- Guarda un correo recibido en la bandeja: encuentra (o abre) su
-- conversación, lo enlaza al contacto si su dirección es de uno solo, y deja
-- constancia en la ficha. Idempotente por el id del proveedor y el
-- Message-ID: Resend reintenta los avisos.
--
-- Solo la llama el servidor (service_role), después de verificar la firma
-- del aviso: confía en la organización que recibe.
create or replace function crm.registrar_correo_entrante(
    organizacion uuid,
    correo jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  proveedor_id text := nullif(correo ->> 'provider_id', '');
  mensaje_id text := nullif(correo ->> 'message_id', '');
  remitente text := lower(btrim(correo ->> 'from_email'));
  automatico boolean := coalesce((correo ->> 'automatic')::boolean, false);
  referencias text[] := coalesce(
    array(select jsonb_array_elements_text(coalesce(correo -> 'references', '[]'::jsonb))),
    '{}'
  );
  respuesta_a text := nullif(correo ->> 'in_reply_to', '');
  enviado timestamp with time zone :=
    coalesce((correo ->> 'sent_at')::timestamp with time zone, now());
  texto text := left(coalesce(correo ->> 'text', ''), 65536);
  conversacion crm.conversations%rowtype;
  existente bigint;
  contacto_id bigint;
  responsable bigint;
  nuevo_mensaje bigint;
  es_nueva boolean := false;
begin
  if remitente is null or remitente = '' then
    raise exception 'registrar_correo_entrante: falta el remitente';
  end if;

  -- Un aviso repetido llega a la vez que el original: que espere.
  perform pg_advisory_xact_lock(
    hashtext(organizacion::text || coalesce(proveedor_id, mensaje_id, remitente))
  );

  select m.conversation_id into existente
  from crm.conversation_messages m
  where m.organization_id = organizacion
    and (m.provider_id = proveedor_id or m.message_id = mensaje_id)
  limit 1;
  if existente is not null then
    return jsonb_build_object('conversation_id', existente, 'duplicate', true);
  end if;

  -- 1. Por las cabeceras de hilo: la respuesta cita un mensaje que ya está.
  if respuesta_a is not null or cardinality(referencias) > 0 then
    select c.* into conversacion
    from crm.conversation_messages m
    join crm.conversations c on c.id = m.conversation_id
    where m.organization_id = organizacion
      and m.message_id = any(referencias || respuesta_a)
    order by m.sent_at desc
    limit 1;
  end if;

  -- 2. Mismo remitente y mismo asunto en los últimos 60 días: muchos
  --    clientes contestan sin cabeceras (o reenvían desde otro programa).
  if conversacion.id is null then
    select c.* into conversacion
    from crm.conversations c
    where c.organization_id = organizacion
      and c.channel = 'email'
      and c.counterpart = remitente
      and crm.asunto_de_hilo(c.subject) = crm.asunto_de_hilo(correo ->> 'subject')
      and c.last_message_at > now() - interval '60 days'
    order by c.last_message_at desc
    limit 1;
  end if;

  if conversacion.id is null then
    -- Solo si la dirección es de un único contacto: con dos, decide una
    -- persona desde la bandeja.
    select min(ct.id), min(ct.sales_id)
    into contacto_id, responsable
    from crm.contacts ct
    where ct.organization_id = organizacion
      and exists (
        select 1 from jsonb_array_elements(coalesce(ct.email_jsonb, '[]'::jsonb)) e
        where lower(btrim(e ->> 'email')) = remitente
      )
    having count(*) = 1;

    insert into crm.conversations (
      organization_id, channel, contact_id, counterpart, counterpart_name,
      subject, status, unread, sales_id, automatic, last_message_at
    )
    values (
      organizacion, 'email', contacto_id, remitente,
      nullif(correo ->> 'from_name', ''), nullif(correo ->> 'subject', ''),
      case when automatico then 'closed' else 'pending' end,
      not automatico, responsable, automatico, enviado
    )
    returning * into conversacion;
    es_nueva := true;
  end if;

  insert into crm.conversation_messages (
    organization_id, conversation_id, direction, from_email, from_name,
    to_emails, cc_emails, subject, body_text, message_id, in_reply_to,
    reference_ids, provider_id, automatic, attachments, sent_at
  )
  values (
    organizacion, conversacion.id, 'in', remitente,
    nullif(correo ->> 'from_name', ''),
    coalesce(array(select jsonb_array_elements_text(coalesce(correo -> 'to', '[]'::jsonb))), '{}'),
    coalesce(array(select jsonb_array_elements_text(coalesce(correo -> 'cc', '[]'::jsonb))), '{}'),
    nullif(correo ->> 'subject', ''), texto, mensaje_id, respuesta_a,
    referencias, proveedor_id, automatico,
    coalesce(correo -> 'attachments', '[]'::jsonb), enviado
  )
  returning id into nuevo_mensaje;

  -- Una respuesta automática se guarda en el hilo, pero no lo reabre.
  update crm.conversations c
  set last_message_at = greatest(c.last_message_at, enviado),
      last_message_preview = left(regexp_replace(texto, '\s+', ' ', 'g'), 200),
      status = case when automatico then c.status else 'pending' end,
      unread = c.unread or not automatico,
      automatic = c.automatic and automatico
  where c.id = conversacion.id;

  -- Constancia en la ficha: cuenta como actividad del contacto.
  if conversacion.contact_id is not null and not automatico then
    insert into crm.contact_notes (
      organization_id, contact_id, text, type, sales_id, date
    )
    values (
      organizacion, conversacion.contact_id,
      left(coalesce(nullif(correo ->> 'subject', '') || E'\n\n', '') || texto, 20000),
      'email', conversacion.sales_id, enviado
    );
  end if;

  return jsonb_build_object(
    'conversation_id', conversacion.id,
    'message_id', nuevo_mensaje,
    'new_conversation', es_nueva,
    'duplicate', false
  );
end;
$$;

revoke all on function crm.registrar_correo_entrante(uuid, jsonb) from public, anon, authenticated;
grant execute on function crm.registrar_correo_entrante(uuid, jsonb) to service_role;
revoke all on function crm.asunto_de_hilo(text) from anon;
