-- Condiciones que leen el texto, no solo los campos.
--
-- Una automatización sabía mirar campos: «cuando se cree un ticket urgente»,
-- «cuando una oportunidad pase a Negociación». Lo que de verdad distingue un
-- caso no cabe en un campo: «cuando el cliente amenace con irse», «cuando
-- mencione a la competencia», «cuando pida una demo». Eso está en el texto.
--
-- El modelo de decisión sabe juzgar esa frase, pero un disparador de Postgres
-- no puede llamar a una API. El camino ya estaba trillado por el correo de
-- las automatizaciones: el disparador ENCOLA y la aplicación drena la cola
-- cada minuto (crm.despachar_correos → /api/correos/despachar). Esto es lo
-- mismo con otra cola.
--
-- Consecuencia que conviene tener presente: una regla con condición actúa con
-- hasta un minuto de retraso, mientras que una sin condición sigue siendo
-- instantánea dentro de la misma transacción.

-- La frase, tal como la escribió la organización. Vacío = regla de siempre.
alter table crm.automations
    add column if not exists condition_text text;

-- Reglas que esperan un juicio del modelo antes de actuar.
create table if not exists crm.automation_pending (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    automation_id bigint not null,
    -- Sobre qué actuaría la acción si la condición se cumple. Se guardan los
    -- ids y no la fila: si algo se borra mientras espera, la acción no debe
    -- resucitarlo (aplicar_accion_de_automatizacion exige contacto).
    contact_id bigint,
    deal_id bigint,
    ticket_id bigint,
    -- El responsable que traía la fila, que es lo que usa «crear tarea».
    sales_id bigint,
    -- El texto que hay que juzgar, congelado al disparar. Si alguien edita el
    -- ticket mientras la fila espera, la decisión tiene que ser sobre lo que
    -- disparó la regla, no sobre lo que diga el ticket un minuto después.
    texto text not null,
    -- El juicio, cuando llega.
    resolved_at timestamp with time zone,
    matched boolean,
    confidence numeric(4, 3),
    -- Reintentos con espera creciente, igual que la cola de correo: que la
    -- API del clasificador esté caída un minuto no debe perder la regla.
    attempts smallint not null default 0,
    max_attempts smallint not null default 4,
    next_attempt_at timestamp with time zone not null default now(),
    created_at timestamp with time zone not null default now()
);

create index if not exists automation_pending_por_resolver_idx
    on crm.automation_pending (next_attempt_at)
    where resolved_at is null;
create index if not exists automation_pending_organization_idx
    on crm.automation_pending (organization_id, created_at desc);

alter table crm.automation_pending enable row level security;

-- Solo lectura, y solo de su organización. Escribe el motor (security
-- definer) y la resuelve el despachador con la clave de servicio. Sin
-- política de escritura, nadie puede inventarse una fila pendiente — que
-- equivaldría a hacer que el CRM ejecute una acción por ti.
drop policy if exists "automation_pending_select_own_org" on crm.automation_pending;
create policy "automation_pending_select_own_org" on crm.automation_pending
    for select to authenticated
    using (organization_id = crm.current_organization_id());

grant select on table crm.automation_pending to authenticated, service_role;
grant insert, update on table crm.automation_pending to service_role;
grant usage, select on sequence crm.automation_pending_id_seq to service_role;

-- El motor de eventos, con la rama nueva: si la regla trae condición, en vez
-- de actuar se encola con el texto de la fila.
create or replace function crm.run_automations() returns trigger
    language plpgsql security definer
    set search_path = ''
    as $$
declare
  org uuid;
  evento text;
  etapa text;
  regla crm.automations;
  contacto bigint;
  responsable bigint;
  oportunidad bigint;
  ticket bigint;
  prioridad text;
  texto_a_juzgar text;
begin
  if pg_trigger_depth() > 1 then
    return null;
  end if;

  org := new.organization_id;
  if org is null then
    return null;
  end if;

  -- Cada tabla lee sus propios campos en su rama: plpgsql resuelve todas
  -- las referencias a new.* de una expresión aunque el «and» no llegue a
  -- ellas, y new.stage no existe en un ticket.
  if tg_op = 'INSERT' then
    evento := 'created';
  elsif tg_table_name = 'deals' then
    if new.stage is distinct from old.stage then
      evento := 'stage_changed';
    else
      return null;
    end if;
  elsif tg_table_name = 'tickets' then
    if new.status = 'closed' and old.status is distinct from 'closed' then
      evento := 'closed';
    else
      return null;
    end if;
  else
    return null;
  end if;

  if tg_table_name = 'contacts' then
    contacto := new.id;
    -- Un contacto recién creado no tiene texto que juzgar: su nota llega
    -- después, en otra transacción. Por eso la interfaz no ofrece condición
    -- para este disparador, y aquí queda null.
    texto_a_juzgar := null;
  elsif tg_table_name = 'deals' then
    etapa := new.stage;
    contacto := new.contact_ids[1];
    oportunidad := new.id;
    texto_a_juzgar := concat_ws(E'\n\n', new.name, new.description);
  elsif tg_table_name = 'tickets' then
    contacto := new.contact_id;
    oportunidad := new.deal_id;
    ticket := new.id;
    prioridad := new.priority;
    texto_a_juzgar := concat_ws(E'\n\n', new.subject, new.description);
  end if;

  for regla in
    select * from crm.automations
     where organization_id = org
       and active
       and trigger_resource = tg_table_name
       and trigger_event = evento
  loop
    begin
      if evento = 'stage_changed'
         and nullif(regla.trigger_params ->> 'stage', '') is not null
         and regla.trigger_params ->> 'stage' is distinct from etapa then
        continue;
      end if;
      -- Un ticket puede filtrar por prioridad («se crea un ticket urgente»).
      if tg_table_name = 'tickets'
         and nullif(regla.trigger_params ->> 'priority', '') is not null
         and regla.trigger_params ->> 'priority' is distinct from prioridad then
        continue;
      end if;

      -- Con condición no se actúa aquí: se encola para que la aplicación le
      -- pregunte al modelo. Sin texto que juzgar la regla no se cumple nunca,
      -- así que no se encola nada (mejor que encolar para responder «no»).
      if nullif(regla.condition_text, '') is not null then
        if nullif(texto_a_juzgar, '') is not null then
          insert into crm.automation_pending
            (organization_id, automation_id, contact_id, deal_id, ticket_id,
             sales_id, texto)
          values
            (org, regla.id, contacto, oportunidad, ticket,
             new.sales_id, texto_a_juzgar);
        end if;
        continue;
      end if;

      if regla.action_type = 'assign_owner' then
        responsable := nullif(regla.action_params ->> 'salesId', '')::bigint;
        if responsable is not null then
          if tg_table_name = 'contacts' then
            update crm.contacts set sales_id = responsable where id = new.id;
          elsif tg_table_name = 'tickets' then
            update crm.tickets set sales_id = responsable where id = new.id;
          else
            update crm.deals set sales_id = responsable where id = new.id;
          end if;
        end if;
      else
        perform crm.aplicar_accion_de_automatizacion(
          regla, contacto, oportunidad, null, null, new.sales_id, ticket
        );
      end if;

    exception when others then
      null;
    end;
  end loop;

  return null;
end;
$$;

-- Aplica (o descarta) una fila de la cola. La llama el despachador con la
-- clave de servicio después de preguntarle al modelo.
--
-- Todo el trabajo de escritura se queda aquí, en SQL, donde ya vivía: la ruta
-- solo aporta el juicio. Y es idempotente — una fila ya resuelta no se vuelve
-- a aplicar, porque un reintento no debe mandar dos correos.
create or replace function crm.resolver_condicion_de_automatizacion(
    pendiente_id bigint,
    se_cumple boolean,
    confianza numeric default null
) returns boolean
    language plpgsql security definer
    set search_path = ''
    as $$
declare
  fila crm.automation_pending;
  regla crm.automations;
  responsable bigint;
begin
  select * into fila
    from crm.automation_pending
   where id = pendiente_id
     and resolved_at is null
   for update;

  if not found then
    return false;
  end if;

  update crm.automation_pending
     set resolved_at = now(),
         matched = se_cumple,
         confidence = confianza
   where id = pendiente_id;

  if not se_cumple then
    return true;
  end if;

  select * into regla
    from crm.automations
   where id = fila.automation_id
     and organization_id = fila.organization_id
     and active;

  -- La regla pudo apagarse o borrarse mientras la fila esperaba: entonces no
  -- se actúa, que es lo que habría querido quien la apagó.
  if not found then
    return true;
  end if;

  if regla.action_type = 'assign_owner' then
    responsable := nullif(regla.action_params ->> 'salesId', '')::bigint;
    if responsable is not null then
      if fila.ticket_id is not null then
        update crm.tickets set sales_id = responsable where id = fila.ticket_id;
      elsif fila.deal_id is not null then
        update crm.deals set sales_id = responsable where id = fila.deal_id;
      elsif fila.contact_id is not null then
        update crm.contacts set sales_id = responsable where id = fila.contact_id;
      end if;
    end if;
  else
    perform crm.aplicar_accion_de_automatizacion(
      regla, fila.contact_id, fila.deal_id, null, null, fila.sales_id,
      fila.ticket_id
    );
  end if;

  return true;
end;
$$;

revoke all on function crm.resolver_condicion_de_automatizacion(bigint, boolean, numeric) from public;
grant all on function crm.resolver_condicion_de_automatizacion(bigint, boolean, numeric) to service_role;

-- Avisa a la aplicación de que hay condiciones que juzgar. Calcado de
-- crm.despachar_correos, por el mismo motivo: la llamada al clasificador
-- vive en TypeScript y Postgres no puede hacerla.
create or replace function crm.despachar_condiciones() returns integer
    language plpgsql security definer
    set search_path = ''
    as $$
declare
  pendientes integer;
  destino text;
  secreto text;
begin
  select count(*) into pendientes
    from crm.automation_pending
   where resolved_at is null
     and attempts < max_attempts
     and next_attempt_at <= now();

  if pendientes = 0 then
    return 0;
  end if;

  select value into destino from crm.internal_settings where key = 'app_url';
  select value into secreto from crm.internal_settings where key = 'dispatch_secret';

  if destino is null or secreto is null then
    return 0;
  end if;

  perform net.http_post(
    url := rtrim(destino, '/') || '/api/automatizaciones/condiciones',
    body := '{}'::jsonb,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'X-Vinqulia-Despacho', secreto
    ),
    timeout_milliseconds := 30000
  );

  return pendientes;
end;
$$;

grant all on function crm.despachar_condiciones() to service_role;

select cron.unschedule('despachar-condiciones')
 where exists (select 1 from cron.job where jobname = 'despachar-condiciones');

select cron.schedule(
  'despachar-condiciones',
  '* * * * *',
  $$select crm.despachar_condiciones();$$
);
