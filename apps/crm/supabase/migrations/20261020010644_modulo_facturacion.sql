-- Módulo de facturación: las ventas de KONTROLIA se facturan desde Vinqulia.
--
-- KontrolIA Auth solo da acceso, maneja planes y cobra con tarjeta (Stripe);
-- nunca factura. El CFDI lo pide Vinqulia a Faqturia por el conector de
-- facturación que ya existe. Reglas del dueño:
--
--   * Una factura POR PRODUCTO: cada contrato es un producto («AduaniaX ·
--     IMMEX») y sus extras van como renglones de la misma factura.
--   * Contrato por transferencia: se factura con método PPD 15 días ANTES de
--     la renovación (renews_on), por el periodo que sigue.
--   * Cobro con tarjeta (lo hace KontrolIA Auth): cuando avisa del cobro
--     (`payment.succeeded`), la factura sale ya PAGADA: método PUE, forma 04
--     (configurable) y total = lo cobrado.
--   * Claves del SAT por omisión 81112106 / E48, configurables por producto.
--   * Por producto: «revisar antes de timbrar» (por omisión) o «timbrar sola».
--   * Sin datos fiscales completos de la empresa no se timbra: la factura se
--     queda en la bandeja como «falta información» y se crea una tarea.
--   * Nada se factura solo para un contrato que no lo tenga encendido
--     (contracts.billing_enabled, apagado en TODOS los existentes).
--
-- New tables:
--   crm.billing_settings  ajustes de facturación por producto ('*' = general)
--   crm.invoice_items     renglones de cada factura que arma el CRM
-- Changed tables:
--   crm.contracts   + billing_enabled
--   crm.invoices    + contrato, periodo, origen, estado de la bandeja, pago,
--                     importes, referencia del origen, problemas, aprobación.
--                     external_id deja de ser obligatorio: una factura en la
--                     bandeja todavía no existe en Faqturia.
--   crm.connectors  + webhook_secret (secreto del aviso de Faqturia)
-- Security (RLS + policies):
--   billing_settings e invoice_items: RLS, lectura de la organización
--   (authenticated, organization_id = crm.current_organization_id()); las
--   escrituras las hace solo el servidor (service_role), por rutas /api que
--   exigen administrador. El puente /api/datos las sirve de solo lectura.
-- Activities and Permissions:
--   Sin permisos nuevos de KontrolIA Auth. Aprobar, descartar, reintentar,
--   «facturar ahora», encender la facturación de un contrato y cambiar los
--   ajustes exigen ser administrador de la organización en el CRM
--   (crm.sales.administrator), como los conectores.
-- Scheduled work:
--   crm.despachar_facturacion() cada hora por pg_cron: hace POST a
--   <app_url>/api/facturacion/procesar con el secreto `billing_cron_secret`
--   de crm.internal_settings. Sin ese secreto no hace nada: la dirección y el
--   secreto los pone quien instala (ver la doc «Módulo de facturación»).

-- ── Contratos: el interruptor ───────────────────────────────────────────
alter table crm.contracts
    add column if not exists billing_enabled boolean not null default false;

-- ── Ajustes por producto ─────────────────────────────────────────────────
create table if not exists crm.billing_settings (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    -- application_slug del contrato (aduaniax, faqturia…) o '*' = general.
    product_key text not null,
    clave_prod_serv text not null default '81112106',
    clave_unidad text not null default 'E48',
    -- Marcadores: {producto}, {plan}, {periodo}.
    concept_template text not null default '{producto} · {plan} · {periodo}',
    tax_rate numeric(5,4) not null default 0.16,
    -- Los precios de los contratos son antes de IVA salvo que se diga aquí.
    prices_include_tax boolean not null default false,
    metodo_pago_transferencia text not null default 'PPD',
    forma_pago_transferencia text not null default '99',
    forma_pago_tarjeta text not null default '04',
    days_before integer not null default 15,
    mode text not null default 'review',
    active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint billing_settings_product_key_check
        check (length(product_key) between 1 and 100),
    constraint billing_settings_clave_prod_serv_check
        check (clave_prod_serv ~ '^\d{8}$'),
    constraint billing_settings_clave_unidad_check
        check (clave_unidad ~ '^[A-Z0-9]{1,5}$'),
    constraint billing_settings_concept_template_check
        check (length(concept_template) between 1 and 300),
    constraint billing_settings_tax_rate_check
        check (tax_rate >= 0 and tax_rate <= 1),
    constraint billing_settings_metodo_check
        check (metodo_pago_transferencia in ('PPD', 'PUE')),
    constraint billing_settings_forma_transferencia_check
        check (forma_pago_transferencia ~ '^\d{2}$'),
    constraint billing_settings_forma_tarjeta_check
        check (forma_pago_tarjeta ~ '^\d{2}$'),
    constraint billing_settings_days_before_check
        check (days_before between 0 and 90),
    constraint billing_settings_mode_check
        check (mode in ('review', 'auto'))
);

create unique index if not exists billing_settings_org_product_uk
    on crm.billing_settings (organization_id, product_key);

-- ── Facturas: lo que necesita la bandeja ─────────────────────────────────
alter table crm.invoices alter column external_id drop not null;

alter table crm.invoices
    add column if not exists contract_id bigint,
    add column if not exists period_start date,
    add column if not exists period_end date,
    add column if not exists origin text not null default 'quote',
    add column if not exists billing_status text,
    add column if not exists payment_method text,
    add column if not exists payment_form text,
    add column if not exists payment_status text,
    add column if not exists paid_amount numeric(14,2) not null default 0,
    add column if not exists paid_at timestamp with time zone,
    add column if not exists due_on date,
    add column if not exists subtotal numeric(14,2),
    add column if not exists tax numeric(14,2),
    -- Referencia del origen: id de la factura de Stripe, de la sesión de
    -- pago de créditos o del evento de la plataforma.
    add column if not exists source_ref text,
    -- Lo que falta para timbrar (rfc, tax_regime, cfdi_use, zipcode…).
    add column if not exists problems jsonb not null default '[]'::jsonb,
    add column if not exists approved_by text,
    add column if not exists approved_at timestamp with time zone,
    add column if not exists discard_reason text,
    -- Cuántas veces una persona pidió timbrarla (aprobar, reintentar): entra
    -- en la clave de idempotencia que se manda a Faqturia, para que un
    -- reintento a mano no reciba la respuesta guardada del intento fallido,
    -- y un reintento automático tras un corte sí.
    add column if not exists stamp_attempts integer not null default 0;

alter table crm.invoices
    drop constraint if exists invoices_contract_id_fkey;
alter table crm.invoices
    add constraint invoices_contract_id_fkey foreign key (contract_id)
        references crm.contracts (id) on delete set null;

alter table crm.invoices
    drop constraint if exists invoices_origin_check,
    drop constraint if exists invoices_billing_status_check,
    drop constraint if exists invoices_payment_status_check,
    drop constraint if exists invoices_payment_method_check;
alter table crm.invoices
    add constraint invoices_origin_check
        check (origin in ('quote', 'contract', 'card', 'credits', 'manual')),
    add constraint invoices_billing_status_check
        check (billing_status is null or billing_status in (
            'pending_review', 'missing_data', 'queued', 'stamping',
            'stamped', 'error', 'cancelled', 'discarded')),
    add constraint invoices_payment_status_check
        check (payment_status is null or payment_status in ('unpaid', 'partial', 'paid')),
    add constraint invoices_payment_method_check
        check (payment_method is null or payment_method in ('PPD', 'PUE'));

-- Las facturas que ya existían (todas de cotizaciones) quedan con el estado
-- de la bandeja que corresponde a su estado en el proveedor.
update crm.invoices
   set billing_status = case status
         when 'stamped' then 'stamped'
         when 'cancelled' then 'cancelled'
         else 'error'
       end
 where billing_status is null;

-- Idempotencia. Índices COMPLETOS, no parciales: PostgREST no puede indicar
-- el predicado en ON CONFLICT (ver 20260917130000) y los nulos no chocan
-- entre sí (las de cotización no tienen contrato ni referencia).
--   * Un contrato, un periodo y un origen: una sola factura, aunque el
--     proceso corra cada hora o alguien pulse «Facturar ahora» dos veces.
--   * Un cobro de tarjeta (id de la factura de Stripe): una sola factura,
--     aunque KontrolIA Auth reintente el aviso.
create unique index if not exists invoices_contract_period_uk
    on crm.invoices (organization_id, contract_id, period_start, origin);
create unique index if not exists invoices_origin_source_ref_uk
    on crm.invoices (organization_id, origin, source_ref);
create index if not exists invoices_billing_status_idx
    on crm.invoices (organization_id, billing_status);
create index if not exists invoices_company_id_idx
    on crm.invoices (company_id);
create index if not exists invoices_contract_id_idx
    on crm.invoices (contract_id);

-- ── Renglones de la factura ──────────────────────────────────────────────
create table if not exists crm.invoice_items (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    invoice_id bigint not null references crm.invoices (id) on delete cascade,
    position integer not null default 0,
    description text not null,
    product_ref text,
    quantity numeric(14,4) not null default 1,
    -- Precio unitario ANTES de IVA, en la moneda de la factura.
    unit_price numeric(14,2) not null default 0,
    amount numeric(14,2) not null default 0,
    clave_prod_serv text not null default '81112106',
    clave_unidad text not null default 'E48',
    tax_rate numeric(5,4) not null default 0.16,
    created_at timestamp with time zone not null default now()
);

create index if not exists invoice_items_invoice_id_idx
    on crm.invoice_items (invoice_id, position);

-- ── Conectores: secreto del aviso de Faqturia ────────────────────────────
-- La tabla ya es SOLO de service_role (guarda la clave de API en claro): el
-- secreto con el que Faqturia firma sus avisos va en una columna propia, que
-- /api/conectores no devuelve nunca (no está entre sus columnas visibles).
alter table crm.connectors
    add column if not exists webhook_secret text;

-- ── RLS y permisos ───────────────────────────────────────────────────────
alter table crm.billing_settings enable row level security;
alter table crm.invoice_items enable row level security;

drop policy if exists "Billing settings are scoped to the organization" on crm.billing_settings;
create policy "Billing settings are scoped to the organization" on crm.billing_settings
    for select to authenticated using (organization_id = crm.current_organization_id());
drop policy if exists "Invoice items are scoped to the organization" on crm.invoice_items;
create policy "Invoice items are scoped to the organization" on crm.invoice_items
    for select to authenticated using (organization_id = crm.current_organization_id());

-- Primero se quita lo que los default privileges conceden solos (grant all,
-- truncate incluido) y luego se da solo lectura: escribe el servidor.
revoke all on table crm.billing_settings from anon;
revoke all on table crm.billing_settings from authenticated;
grant select on table crm.billing_settings to authenticated;
grant select, insert, update, delete on table crm.billing_settings to service_role;
grant usage, select on sequence crm.billing_settings_id_seq to service_role;

revoke all on table crm.invoice_items from anon;
revoke all on table crm.invoice_items from authenticated;
grant select on table crm.invoice_items to authenticated;
grant select, insert, update, delete on table crm.invoice_items to service_role;
grant usage, select on sequence crm.invoice_items_id_seq to service_role;

-- ── Proceso de cada hora ─────────────────────────────────────────────────
-- Planear las facturas de los contratos, timbrar las aprobadas y preguntar
-- a Faqturia por las que siguen sin pagar necesita HTTP hacia Faqturia y la
-- lógica vive en TypeScript, así que la base solo despierta a la ruta.
-- No escribe ni la dirección ni el secreto: los lee de crm.internal_settings
-- (`app_url`, que ya existe, y `billing_cron_secret`, que pone quien instala
-- con el mismo valor que FACTURACION_CRON_SECRET del servidor). Sin secreto,
-- o sin ninguna organización con Faqturia conectada, no hace nada.
create or replace function crm.despachar_facturacion() returns integer
    language plpgsql security definer
    set search_path = ''
    as $$
declare
  destino text;
  secreto text;
begin
  select value into destino from crm.internal_settings where key = 'app_url';
  select value into secreto from crm.internal_settings where key = 'billing_cron_secret';

  if coalesce(destino, '') = '' or coalesce(secreto, '') = '' then
    return 0;
  end if;

  if not exists (
    select 1 from crm.connectors
     where family = 'invoicing' and provider = 'faqturia'
  ) then
    return 0;
  end if;

  perform net.http_post(
    url := rtrim(destino, '/') || '/api/facturacion/procesar',
    body := '{}'::jsonb,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'X-Vinqulia-Facturacion', secreto
    ),
    timeout_milliseconds := 60000
  );

  return 1;
end;
$$;

revoke all on function crm.despachar_facturacion() from public;
revoke all on function crm.despachar_facturacion() from anon;
revoke all on function crm.despachar_facturacion() from authenticated;
grant execute on function crm.despachar_facturacion() to service_role;

select cron.unschedule('despachar-facturacion')
 where exists (select 1 from cron.job where jobname = 'despachar-facturacion');

select cron.schedule(
  'despachar-facturacion',
  '7 * * * *',
  $$select crm.despachar_facturacion();$$
);
