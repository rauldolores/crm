-- Uso del cliente y «cliente en riesgo» (clientes de KONTROLIA que llegan de
-- KontrolIA Auth).
--
-- 1. Uso: KontrolIA Auth manda en la foto de cada cliente (`snapshot.usage`)
--    el consumo del mes actual y del anterior por producto y límite (páginas,
--    timbres, pedimentos…): cuánto usó, cuánto incluye su plan (null = sin
--    límite) y el precio de cada unidad de más. La integración
--    (aplicarKontroliaAuth.ts) lo guarda en crm.customer_usage y la pestaña
--    «Cliente» lo enseña junto con los usuarios activos y el último acceso.
--
-- 2. Cliente en riesgo. Reglas del dueño:
--    · Si nadie de la empresa entra en 14 días (ajustable), la empresa pasa a
--      la etapa 'at-risk' y se abre una tarea de llamada para el responsable
--      de la cuenta. Cuando alguien vuelve a entrar, regresa a 'customer'.
--    · Solo empresas que llegan de KontrolIA Auth (source 'kontrolia_auth')
--      con al menos un contrato activo y en etapa 'customer'.
--    · Nunca pisa una etapa que puso una persona: el sistema solo regresa lo
--      que él mismo marcó (crm.customer_risk). Si una persona la mueve a
--      otra etapa, el sistema se olvida de ella; si la regresa a 'customer'
--      sin que nadie haya entrado, no se vuelve a marcar (ni a abrir otra
--      tarea) hasta que alguien entre y vuelva a dejar de entrar.
--    · «Entrar» = contacts.last_seen, que la integración llena con el último
--      inicio de sesión de cada usuario (last_sign_in_at). Cuenta el más
--      reciente de los contactos no archivados de la empresa; si nadie ha
--      entrado nunca, cuenta desde el alta de la empresa.
--    · La etapa no lleva bitácora propia: el cambio sale, como cualquier
--      otro cambio de empresa, por el disparador de webhooks
--      (notify_webhooks_companies). No se agregan notas automáticas (ver
--      20260928161009_sin_notas_automaticas.sql).
--
-- Lo corre pg_cron una vez al día, a las 13:30 UTC (7:30 en México), con
-- crm.revisar_clientes_en_riesgo(): SQL puro e idempotente (correrla dos
-- veces el mismo día no marca ni abre tareas de más).
--
-- New Tables:
--   crm.customer_usage  consumo por empresa × producto × límite × mes. Lo
--                       escribe solo la integración (clave de servicio); se
--                       guardan el mes actual y el anterior. El precio de lo
--                       de más (overage_price_amount) va en PESOS: la
--                       integración convierte los centavos del origen, como
--                       el resto de importes.
--   crm.customer_risk   las empresas que el sistema marcó en riesgo: cuándo,
--                       cuál era el último acceso entonces y la tarea que
--                       abrió. Una por empresa.
-- Configuración (crm.configuration.config, sin columna nueva):
--   risk = {active, inactivityDays}. Si falta, valen los de fábrica (activo,
--   14 días). No se reescribe ninguna configuración existente.
-- Security (RLS + policies):
--   Las dos tablas: RLS, solo lectura para la organización
--   (crm.current_organization_id()); escribe solo service_role (la
--   integración) y la función (security definer). En el puente /api/datos
--   son de solo lectura. Funciones nuevas: revoke de public, anon y
--   authenticated; execute solo para service_role.
-- Activities and Permissions:
--   Sin permisos nuevos. Los ajustes (config.risk) se guardan como el resto
--   de la configuración: solo administradores de la organización.

-- ── 1. Uso del cliente ───────────────────────────────────────────────────
create table if not exists crm.customer_usage (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    company_id bigint not null references crm.companies (id) on delete cascade,
    -- Producto de KONTROLIA (aduaniax, facturacion…), como en contracts.
    application_slug text not null,
    -- Límite del plan (ctm_paginas, timbres…) y su nombre legible.
    limit_key text not null,
    description text,
    -- Primer día del mes que se mide.
    period_start date not null,
    used numeric not null default 0,
    -- Lo que incluye el plan; null = sin límite.
    included numeric,
    -- Precio de cada unidad de más, en pesos (null = no se cobra aparte).
    overage_price_amount numeric,
    currency text,
    updated_at timestamp with time zone not null default now()
);
-- Completo (sin predicado): PostgREST lo usa en ON CONFLICT.
create unique index if not exists customer_usage_uk
    on crm.customer_usage (organization_id, company_id, application_slug, limit_key, period_start);
create index if not exists customer_usage_company_idx
    on crm.customer_usage (company_id, period_start desc);

alter table crm.customer_usage enable row level security;
drop policy if exists "customer_usage_select_own_org" on crm.customer_usage;
create policy "customer_usage_select_own_org" on crm.customer_usage
    for select to authenticated
    using (organization_id = crm.current_organization_id());

revoke all on table crm.customer_usage from anon;
revoke all on table crm.customer_usage from authenticated;
grant select on table crm.customer_usage to authenticated;
grant select, insert, update, delete on table crm.customer_usage to service_role;
grant usage, select on sequence crm.customer_usage_id_seq to service_role;

-- ── 2. Lo que marcó el sistema ───────────────────────────────────────────
create table if not exists crm.customer_risk (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    company_id bigint not null references crm.companies (id) on delete cascade,
    -- Último acceso de alguien de la empresa cuando se marcó (null = nadie
    -- había entrado nunca).
    last_seen_at timestamp with time zone,
    -- Los días sin actividad que valían al marcarla.
    inactivity_days integer not null,
    flagged_at timestamp with time zone not null default now(),
    -- La tarea que se abrió (null si la empresa no tenía contactos o si
    -- después se borró).
    task_id bigint references crm.tasks (id) on delete set null
);
create unique index if not exists customer_risk_company_uk
    on crm.customer_risk (company_id);
create index if not exists customer_risk_organization_id_idx
    on crm.customer_risk (organization_id);

alter table crm.customer_risk enable row level security;
drop policy if exists "customer_risk_select_own_org" on crm.customer_risk;
create policy "customer_risk_select_own_org" on crm.customer_risk
    for select to authenticated
    using (organization_id = crm.current_organization_id());

revoke all on table crm.customer_risk from anon;
revoke all on table crm.customer_risk from authenticated;
grant select on table crm.customer_risk to authenticated;
grant select, insert, update, delete on table crm.customer_risk to service_role;
grant usage, select on sequence crm.customer_risk_id_seq to service_role;

-- ── 3. Ajustes ───────────────────────────────────────────────────────────

-- Los ajustes de la organización con los de fábrica donde falten. Misma
-- regla que ajustesDeRiesgo() en src/components/crm/customers/usoDelCliente.ts:
-- días = entero de 1 a 365 (número o texto); lo demás vale 14.
create or replace function crm.ajustes_de_riesgo(p_config jsonb) returns jsonb
    language plpgsql immutable
    set search_path = ''
    as $$
declare
  r jsonb := p_config -> 'risk';
  dias integer := 14;
begin
  if r is null or jsonb_typeof(r) <> 'object' then
    r := '{}'::jsonb;
  end if;
  if jsonb_typeof(r -> 'inactivityDays') in ('number', 'string')
     and (r ->> 'inactivityDays') ~ '^[0-9]{1,4}$' then
    dias := (r ->> 'inactivityDays')::integer;
    if dias < 1 then
      dias := 14;
    end if;
    dias := least(dias, 365);
  end if;
  return jsonb_build_object(
    'active', (case when jsonb_typeof(r -> 'active') = 'boolean'
                    then (r ->> 'active')::boolean else true end),
    'inactivityDays', dias
  );
end;
$$;

-- ── 4. El proceso ────────────────────────────────────────────────────────
create or replace function crm.revisar_clientes_en_riesgo() returns jsonb
    language plpgsql security definer
    set search_path = ''
    as $$
declare
  org uuid;
  cfg jsonb;
  ajustes jsonb;
  dias integer;
  tipo_tarea text;
  k record;
  f record;
  marca bigint;
  contacto bigint;
  tarea bigint;
  sin_entrar integer;
  texto text;
  marcadas integer := 0;
  recuperadas integer := 0;
  olvidadas integer := 0;
  errores integer := 0;
begin
  -- 1. Regresar lo que marcó el sistema. Va primero y no mira si la
  --    revisión está encendida: una organización que la apaga no debe
  --    quedarse con clientes en riesgo para siempre.
  for f in
    select r.id, r.company_id, r.organization_id, e.lifecycle_stage,
           (select max(ct.last_seen)
              from crm.contacts ct
             where ct.company_id = r.company_id
               and ct.organization_id = r.organization_id
               and ct.archived_at is null) as ultimo
      from crm.customer_risk r
      join crm.companies e on e.id = r.company_id
  loop
    begin
      select c.config into cfg from crm.configuration c where c.organization_id = f.organization_id;
      dias := (crm.ajustes_de_riesgo(cfg) ->> 'inactivityDays')::integer;

      if f.ultimo is not null and f.ultimo >= now() - make_interval(days => dias) then
        -- Alguien volvió a entrar. Solo se regresa la etapa si sigue en la
        -- que puso el sistema.
        if f.lifecycle_stage = 'at-risk' then
          update crm.companies
             set lifecycle_stage = 'customer'
           where id = f.company_id
             and lifecycle_stage = 'at-risk';
          recuperadas := recuperadas + 1;
        end if;
        delete from crm.customer_risk where id = f.id;
      elsif f.lifecycle_stage is distinct from 'at-risk'
            and f.lifecycle_stage is distinct from 'customer' then
        -- Una persona (o la integración, al perderse el cliente) la movió a
        -- otra etapa: ya no es asunto del sistema.
        delete from crm.customer_risk where id = f.id;
        olvidadas := olvidadas + 1;
      end if;
      -- Sigue sin entrar (en riesgo, o regresada a mano a cliente): se
      -- conserva la marca para no volver a marcarla ni abrir otra tarea.
    exception when others then
      errores := errores + 1;
      raise warning 'Cliente en riesgo, revisión de la empresa %: %', f.company_id, sqlerrm;
    end;
  end loop;

  -- 2. Marcar a quien lleva los días sin entrar.
  for org in
    select distinct e.organization_id
      from crm.companies e
     where e.source = 'kontrolia_auth'
       and e.lifecycle_stage = 'customer'
  loop
    begin
      select c.config into cfg from crm.configuration c where c.organization_id = org;
      ajustes := crm.ajustes_de_riesgo(cfg);
      continue when not (ajustes ->> 'active')::boolean;
      dias := (ajustes ->> 'inactivityDays')::integer;
      -- Llamada si la organización tiene ese tipo de tarea (o usa los de
      -- fábrica); si no, sin tipo. Igual que las renovaciones.
      tipo_tarea := (case
        when coalesce(jsonb_typeof(cfg -> 'taskTypes'), '') <> 'array'
          or exists (
            select 1 from jsonb_array_elements(
              case when jsonb_typeof(cfg -> 'taskTypes') = 'array'
                   then cfg -> 'taskTypes' else '[]'::jsonb end) t
             where t ->> 'value' = 'call')
        then 'call' else null end);

      for k in
        select e.id, e.name, e.sales_id, e.created_at, a.ultimo
          from crm.companies e
          left join lateral (
            select max(ct.last_seen) as ultimo
              from crm.contacts ct
             where ct.company_id = e.id
               and ct.organization_id = org
               and ct.archived_at is null
          ) a on true
         where e.organization_id = org
           and e.source = 'kontrolia_auth'
           and e.lifecycle_stage = 'customer'
           and exists (
             select 1 from crm.contracts c
              where c.company_id = e.id
                and c.organization_id = org
                and c.status = 'active'
           )
           and not exists (
             select 1 from crm.customer_risk r where r.company_id = e.id
           )
           and coalesce(a.ultimo, e.created_at) < now() - make_interval(days => dias)
         order by e.id
      loop
        begin
          marca := null;
          insert into crm.customer_risk (organization_id, company_id, last_seen_at, inactivity_days)
          values (org, k.id, k.ultimo, dias)
          on conflict (company_id) do nothing
          returning id into marca;
          continue when marca is null;

          update crm.companies
             set lifecycle_stage = 'at-risk'
           where id = k.id
             and lifecycle_stage = 'customer';

          -- Días en hora de México, como se leen las fechas en el resto del
          -- CRM.
          sin_entrar := (now() at time zone 'America/Mexico_City')::date
            - (coalesce(k.ultimo, k.created_at) at time zone 'America/Mexico_City')::date;
          texto := (case
            when k.ultimo is null
            then 'Cliente sin actividad: nadie de ' || k.name
                 || ' ha entrado desde que se dio de alta, hace ' || sin_entrar || ' días.'
            else 'Cliente sin actividad: nadie de ' || k.name
                 || ' ha entrado en ' || sin_entrar || ' días.'
            end) || ' Llamar para saber si necesita ayuda.';

          contacto := (
            select ct.id from crm.contacts ct
             where ct.company_id = k.id
               and ct.organization_id = org
               and ct.archived_at is null
             order by ct.last_seen desc nulls last, ct.id
             limit 1
          );
          tarea := null;
          if contacto is not null then
            insert into crm.tasks (organization_id, contact_id, text, type, due_date, sales_id)
            values (org, contacto, texto, tipo_tarea,
                    current_date::timestamp with time zone, k.sales_id)
            returning id into tarea;
            update crm.customer_risk set task_id = tarea where id = marca;
          end if;
          marcadas := marcadas + 1;
        exception when others then
          errores := errores + 1;
          raise warning 'Cliente en riesgo, empresa %: %', k.id, sqlerrm;
        end;
      end loop;
    exception when others then
      errores := errores + 1;
      raise warning 'Clientes en riesgo de la organización %: %', org, sqlerrm;
    end;
  end loop;

  return jsonb_build_object(
    'marcadas', marcadas,
    'recuperadas', recuperadas,
    'olvidadas', olvidadas,
    'errores', errores
  );
end;
$$;

-- ── 5. Permisos ──────────────────────────────────────────────────────────
revoke all on function crm.ajustes_de_riesgo(jsonb) from public, anon, authenticated;
revoke all on function crm.revisar_clientes_en_riesgo() from public, anon, authenticated;

grant execute on function crm.ajustes_de_riesgo(jsonb) to service_role;
grant execute on function crm.revisar_clientes_en_riesgo() to service_role;

-- ── 6. Una vez al día, 13:30 UTC (7:30 en México) ────────────────────────
select cron.unschedule('clientes-en-riesgo')
 where exists (select 1 from cron.job where jobname = 'clientes-en-riesgo');

select cron.schedule(
  'clientes-en-riesgo',
  '30 13 * * *',
  $$select crm.revisar_clientes_en_riesgo();$$
);
