-- Integración con KontrolIA Auth: los clientes de KONTROLIA, al día solos.
--
-- KontrolIA Auth (el login y la facturación de AduaniaX, Faqturia, Vinqulia y
-- Nodia Agents) avisa con un POST cada vez que cambia un cliente, y cada aviso
-- trae la FOTO COMPLETA de la organización: sus usuarios, la suscripción de
-- cada aplicación (plan, extras, vigencia, precio), las renovaciones con su
-- pago y el historial. /api/integraciones/kontrolia-auth la convierte en
-- empresa, contactos, contratos, compras e historial del contrato. Ver
-- doc/src/content/docs/developers/integracion-kontrolia-auth.mdx.
--
-- Todo lo que llega guarda de dónde vino (`source = 'kontrolia_auth'`) y con
-- qué identificador (`external_id`), como el resto del módulo Clientes: un
-- aviso repetido o fuera de orden actualiza, nunca duplica.

-- ── Empresas y contactos: de dónde vinieron ──────────────────────────────
-- Índice único COMPLETO, no parcial: PostgREST no puede indicar el predicado
-- en ON CONFLICT (ver 20260917130000). Los external_id nulos (altas a mano)
-- no chocan entre sí.
alter table crm.companies add column if not exists source text;
alter table crm.companies add column if not exists external_id text;
create unique index if not exists companies_source_external_uk
    on crm.companies (organization_id, source, external_id);

alter table crm.contacts add column if not exists source text;
alter table crm.contacts add column if not exists external_id text;
create unique index if not exists contacts_source_external_uk
    on crm.contacts (organization_id, source, external_id);

-- ── Contratos: qué plan de qué producto ─────────────────────────────────
-- `application_slug` dice de qué producto es el contrato (aduaniax,
-- facturacion…), `plan_slug`/`plan_name` qué plan tiene hoy, `provider` cómo
-- se cobra (manual = por contrato, stripe = con tarjeta) y `addons` los
-- extras tal como los manda el origen (nombre, si vienen incluidos en el
-- plan, precio en centavos, vigencia).
alter table crm.contracts add column if not exists application_slug text;
alter table crm.contracts add column if not exists plan_slug text;
alter table crm.contracts add column if not exists plan_name text;
alter table crm.contracts add column if not exists provider text;
alter table crm.contracts add column if not exists addons jsonb not null default '[]'::jsonb;

-- ── Historial del contrato ──────────────────────────────────────────────
-- Cada cambio de plan, renovación, extra o cortesía, como pasó en el origen.
-- No lo escribe ninguna persona: solo la integración (con service_role), así
-- que el puente /api/datos lo sirve de solo lectura.
create table if not exists crm.contract_events (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    contract_id bigint references crm.contracts (id) on delete cascade,
    company_id bigint references crm.companies (id) on delete cascade,
    -- manual.assigned, addon.added, renewal, stripe.invoice.paid…
    type text not null,
    occurred_at timestamp with time zone not null,
    title text not null,
    detail jsonb not null default '{}'::jsonb,
    amount numeric,
    currency text,
    source text not null,
    external_id text not null,
    created_at timestamp with time zone not null default now()
);

create unique index if not exists contract_events_source_external_uk
    on crm.contract_events (organization_id, source, external_id);
create index if not exists contract_events_company_idx
    on crm.contract_events (company_id, occurred_at desc);
create index if not exists contract_events_contract_idx
    on crm.contract_events (contract_id, occurred_at desc);

alter table crm.contract_events enable row level security;

drop policy if exists "Contract events are scoped to the organization" on crm.contract_events;
create policy "Contract events are scoped to the organization" on crm.contract_events
    for select to authenticated using (organization_id = crm.current_organization_id());
drop policy if exists "Contract events are created in the organization" on crm.contract_events;
create policy "Contract events are created in the organization" on crm.contract_events
    for insert to authenticated with check (organization_id = crm.current_organization_id());
drop policy if exists "Contract events are updated within the organization" on crm.contract_events;
create policy "Contract events are updated within the organization" on crm.contract_events
    for update to authenticated using (organization_id = crm.current_organization_id())
    with check (organization_id = crm.current_organization_id());
drop policy if exists "Contract events are deleted within the organization" on crm.contract_events;
create policy "Contract events are deleted within the organization" on crm.contract_events
    for delete to authenticated using (organization_id = crm.current_organization_id());

grant select, insert, update, delete on table crm.contract_events to anon, authenticated, service_role;
grant usage, select on sequence crm.contract_events_id_seq to anon, authenticated, service_role;

-- ── Bitácora de avisos recibidos ────────────────────────────────────────
-- Un renglón por aviso (el id del evento es el mismo en cada reintento): qué
-- llegó, cuándo y si se aplicó. `snapshot_generated_at` permite ignorar una
-- foto más vieja que la última aplicada de esa organización — los reintentos
-- pueden llegar fuera de orden.
-- SOLO service_role: sin políticas y fuera del puente /api/datos.
create table if not exists crm.integration_events (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    source text not null,
    event_id text not null,
    type text,
    -- Organización del sistema de origen a la que se refiere el aviso.
    external_organization_id text,
    snapshot_generated_at timestamp with time zone,
    received_at timestamp with time zone not null default now(),
    status text not null check (status in ('ok', 'error')),
    error text
);

create unique index if not exists integration_events_event_uk
    on crm.integration_events (organization_id, source, event_id);
create index if not exists integration_events_external_org_idx
    on crm.integration_events (organization_id, source, external_organization_id, snapshot_generated_at desc);

alter table crm.integration_events enable row level security;

grant select, insert, update, delete on table crm.integration_events to service_role;
grant usage, select on sequence crm.integration_events_id_seq to service_role;
-- Lo que los default privileges del esquema conceden solos a toda tabla nueva.
revoke all on table crm.integration_events from anon;
revoke all on table crm.integration_events from authenticated;
revoke all on sequence crm.integration_events_id_seq from anon;
revoke all on sequence crm.integration_events_id_seq from authenticated;

-- ── Resumen del cliente: de dónde viene la empresa ──────────────────────
-- Se agregan `source` y `external_id` AL FINAL (create or replace view solo
-- admite columnas nuevas al final) para que la pestaña «Cliente» sepa si la
-- empresa se sincroniza sola desde KontrolIA.
create or replace view crm.customer_summary with (security_invoker = on) as
select
    c.id,
    c.organization_id,
    c.name,
    c.lifecycle_stage,
    c.sales_id,
    coalesce(p.nb_purchases, 0) as nb_purchases,
    coalesce(p.total_spent, 0) as total_spent,
    p.first_purchase_on,
    p.last_purchase_on,
    coalesce(k.nb_active_contracts, 0) as nb_active_contracts,
    coalesce(k.recurring_amount, 0) as recurring_amount,
    k.next_renewal_on,
    coalesce(t.open_tickets, 0) as open_tickets,
    coalesce(t.overdue_tickets, 0) as overdue_tickets,
    (coalesce(t.open_tickets, 0) >= 3 or coalesce(t.overdue_tickets, 0) >= 1) as at_risk,
    coalesce(k.nb_recurring_contracts, 0) as nb_recurring_contracts,
    coalesce(k.nb_one_time_contracts, 0) as nb_one_time_contracts,
    coalesce(k.one_time_amount, 0) as one_time_amount,
    coalesce(g.nb_won_deals, 0) as nb_won_deals,
    coalesce(g.won_amount, 0) as won_amount,
    c.source,
    c.external_id
from crm.companies c
left join lateral (
    select count(*) as nb_purchases,
           sum(amount) as total_spent,
           min(purchased_on) as first_purchase_on,
           max(purchased_on) as last_purchase_on
      from crm.purchases
     where company_id = c.id and status <> 'cancelled'
) p on true
left join lateral (
    select
        count(*) as nb_active_contracts,
        count(*) filter (where billing_period in ('monthly', 'quarterly', 'yearly'))
            as nb_recurring_contracts,
        count(*) filter (where billing_period is null
                            or billing_period not in ('monthly', 'quarterly', 'yearly'))
            as nb_one_time_contracts,
        sum(amount) filter (where billing_period in ('monthly', 'quarterly', 'yearly'))
            as recurring_amount,
        sum(amount) filter (where billing_period is null
                               or billing_period not in ('monthly', 'quarterly', 'yearly'))
            as one_time_amount,
        min(renews_on) filter (
            where renews_on is not null
              and billing_period in ('monthly', 'quarterly', 'yearly')
        ) as next_renewal_on
      from crm.contracts
     where company_id = c.id and status = 'active'
) k on true
left join lateral (
    select count(*) as nb_won_deals,
           sum(d.amount) as won_amount
      from crm.deals d
     where d.company_id = c.id
       and d.organization_id = c.organization_id
       and d.archived_at is null
       and coalesce(
             (
               select embudo -> 'pipelineStatuses' ? d.stage
                 from crm.configuration cfg
                      cross join lateral jsonb_array_elements(
                        coalesce(cfg.config -> 'dealPipelines', '[]'::jsonb)
                      ) as embudo
                where cfg.organization_id = d.organization_id
                  and embudo ->> 'value' = coalesce(d.pipeline, 'ventas')
                limit 1
             ),
             false
           )
) g on true
left join lateral (
    select count(*) as open_tickets,
           count(*) filter (where due_at < now()) as overdue_tickets
      from crm.tickets
     where company_id = c.id and status <> 'closed'
) t on true;

grant select on table crm.customer_summary to anon, authenticated, service_role;

-- ── Fusión de empresas ──────────────────────────────────────────────────
-- crm.merge_companies borra la perdedora, y contract_events cuelga de la
-- empresa con on delete cascade: sin moverlo, fusionar un cliente borraría
-- su historial. Además la ganadora hereda el vínculo con KontrolIA Auth.
create or replace function crm.merge_companies(loser_id bigint, winner_id bigint)
    returns bigint
    language plpgsql security definer
    set search_path = ''
as $$
declare
  winner crm.companies%rowtype;
  loser crm.companies%rowtype;
  winner_affiliate bigint;
  loser_affiliate bigint;
  afiliado_final bigint;
begin
  if loser_id = winner_id then
    raise exception 'Una empresa no se puede fusionar consigo misma';
  end if;
  select * into winner from crm.companies where id = winner_id;
  select * into loser from crm.companies where id = loser_id;
  if winner.id is null or loser.id is null then
    raise exception 'Empresa no encontrada';
  end if;
  if winner.organization_id <> loser.organization_id then
    raise exception 'Las empresas son de organizaciones distintas';
  end if;

  -- La fusión mueve atribuciones a propósito: se autoriza para toda la
  -- transacción (ver crm.conservar_afiliado_de_referencia).
  perform set_config('crm.cambio_de_afiliado_autorizado', 'on', true);

  -- 1. Todo lo que apunta a la perdedora pasa a la ganadora. Borrarla sin
  -- esto arrastraría contactos, oportunidades y tickets (on delete cascade)
  -- o dejaría cotizaciones y facturas sin empresa (set null).
  update crm.contacts set company_id = winner_id where company_id = loser_id;
  update crm.deals set company_id = winner_id where company_id = loser_id;
  update crm.tickets set company_id = winner_id where company_id = loser_id;
  update crm.quotes set company_id = winner_id where company_id = loser_id;
  update crm.contracts set company_id = winner_id where company_id = loser_id;
  update crm.purchases set company_id = winner_id where company_id = loser_id;
  update crm.invoices set company_id = winner_id where company_id = loser_id;
  update crm.contract_events set company_id = winner_id where company_id = loser_id;
  -- Si la ganadora ya tiene afiliado, la atribución vigente de la perdedora
  -- termina aquí: una empresa sólo puede tener una vigente.
  if winner.referred_by_affiliate_id is not null then
    update crm.affiliate_attributions
       set status = 'reemplazada', ended_at = now(), end_reason = 'Fusión de empresas'
     where company_id = loser_id and status = 'vigente';
  end if;
  update crm.affiliate_attributions set company_id = winner_id where company_id = loser_id;

  -- 2. Afiliados: la ganadora conserva el suyo. Si no tiene, hereda el de
  -- la perdedora; si las dos tienen, los referidos por el de la perdedora
  -- pasan al de la ganadora y el otro se va con ella (cascade).
  select id into winner_affiliate from crm.affiliates where company_id = winner_id order by id limit 1;
  select id into loser_affiliate from crm.affiliates where company_id = loser_id order by id limit 1;
  if loser_affiliate is not null then
    if winner_affiliate is null then
      update crm.affiliates set company_id = winner_id where company_id = loser_id;
    else
      update crm.companies set referred_by_affiliate_id = winner_affiliate
        where referred_by_affiliate_id = loser_affiliate;
      update crm.affiliate_attributions set affiliate_id = winner_affiliate
        where affiliate_id = loser_affiliate;
    end if;
  end if;

  -- 3. Ficha: la ganadora manda; lo que le falte lo aporta la perdedora.
  -- Los enlaces de contexto se juntan y los campos personalizados también
  -- (los de la ganadora pisan a los de la perdedora).
  update crm.companies set
    sector = coalesce(winner.sector, loser.sector),
    size = coalesce(winner.size, loser.size),
    linkedin_url = coalesce(winner.linkedin_url, loser.linkedin_url),
    website = coalesce(winner.website, loser.website),
    phone_number = coalesce(winner.phone_number, loser.phone_number),
    address = coalesce(winner.address, loser.address),
    zipcode = coalesce(winner.zipcode, loser.zipcode),
    city = coalesce(winner.city, loser.city),
    state_abbr = coalesce(winner.state_abbr, loser.state_abbr),
    country = coalesce(winner.country, loser.country),
    sales_id = coalesce(winner.sales_id, loser.sales_id),
    description = coalesce(winner.description, loser.description),
    revenue = coalesce(winner.revenue, loser.revenue),
    tax_identifier = coalesce(winner.tax_identifier, loser.tax_identifier),
    tax_regime = coalesce(winner.tax_regime, loser.tax_regime),
    cfdi_use = coalesce(winner.cfdi_use, loser.cfdi_use),
    logo = coalesce(winner.logo, loser.logo),
    lifecycle_stage = coalesce(winner.lifecycle_stage, loser.lifecycle_stage),
    referred_by_affiliate_id = coalesce(winner.referred_by_affiliate_id, loser.referred_by_affiliate_id),
    context_links = (
      coalesce(winner.context_links::jsonb, '[]'::jsonb)
      || coalesce(loser.context_links::jsonb, '[]'::jsonb)
    )::json,
    custom_fields = coalesce(loser.custom_fields, '{}'::jsonb) || coalesce(winner.custom_fields, '{}'::jsonb),
    created_at = least(winner.created_at, loser.created_at)
  where id = winner_id;

  -- 3b. Historial: si las dos traían atribución distinta, la de la
  -- perdedora deja de estar vigente (ganó la de la ganadora).
  select referred_by_affiliate_id into afiliado_final from crm.companies where id = winner_id;
  update crm.affiliate_attributions
     set status = 'reemplazada',
         ended_at = now(),
         end_reason = 'Fusión de empresas'
   where company_id = winner_id
     and status = 'vigente'
     and affiliate_id is distinct from afiliado_final;

  -- 4. Adiós a la perdedora.
  delete from crm.companies where id = loser_id;

  -- 5. Si la perdedora llegaba de una integración (KontrolIA Auth) y la
  -- ganadora no, la ganadora hereda el vínculo: si no, el siguiente aviso
  -- volvería a crear la empresa. Va después del borrado por el índice único
  -- (organization_id, source, external_id).
  if winner.external_id is null and loser.external_id is not null then
    update crm.companies
       set source = loser.source, external_id = loser.external_id
     where id = winner_id;
  end if;

  perform set_config('crm.cambio_de_afiliado_autorizado', 'off', true);
  return winner_id;
end;
$$;

revoke all on function crm.merge_companies(bigint, bigint) from public;
grant execute on function crm.merge_companies(bigint, bigint) to service_role;
