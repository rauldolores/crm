-- Una acción ejecutada sobre muchos registros a la vez.
--
-- Guarda el encargo, NO el estado de cada envío: ese ya vive en la cola de
-- correo (sent_at, attempts, last_error), y duplicarlo en una tabla de
-- renglones daría dos verdades que se desincronizan. El avance se cuenta
-- agrupando crm.email_outbox por bulk_job_id.
--
-- Existe para tres cosas que una barra de progreso en el navegador no da:
-- cerrar el diálogo sin cancelar nada, volver a mirarlo mañana, y saber
-- quién lanzó un envío de cinco mil correos.
create table if not exists crm.bulk_jobs (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    sales_id bigint,
    resource text not null,
    action_type text not null,
    action_params jsonb not null default '{}'::jsonb,
    target jsonb not null default '{}'::jsonb,
    requested integer not null default 0,
    enqueued integer not null default 0,
    -- Motivo -> cuántos. Lo valioso de un envío masivo no es el contador, es
    -- saber por qué unos cuantos se quedaron fuera.
    skipped_reasons jsonb not null default '{}'::jsonb,
    created_at timestamp with time zone not null default now()
);

create index if not exists bulk_jobs_organization_id_idx
    on crm.bulk_jobs (organization_id, created_at desc);

-- La acción masiva que encoló cada correo, para contar el avance.
alter table crm.email_outbox
    add column if not exists bulk_job_id bigint;

create index if not exists email_outbox_bulk_job_idx
    on crm.email_outbox (bulk_job_id)
    where bulk_job_id is not null;

alter table crm.bulk_jobs enable row level security;

-- Solo lectura: las crea la ruta /api/acciones-masivas, que comprueba que
-- quien las lanza es administrador. Servirlas para escritura dejaría a
-- cualquiera con sesión encolar cinco mil correos.
drop policy if exists "Bulk jobs are scoped to the organization" on crm.bulk_jobs;
create policy "Bulk jobs are scoped to the organization" on crm.bulk_jobs
    for select to authenticated
    using (organization_id = crm.current_organization_id());

grant select on table crm.bulk_jobs to anon, authenticated, service_role;
grant usage, select on sequence crm.bulk_jobs_id_seq to anon, authenticated, service_role;
