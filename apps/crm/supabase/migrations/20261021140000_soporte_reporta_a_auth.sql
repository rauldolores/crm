-- Las horas de soporte también se cuentan en KontrolIA Auth.
--
-- La bolsa de horas es un extra de Auth con el límite `soporte` en HORAS
-- (10 la Básica, 15 la Premium; hora de más $400). Auth enseña ese consumo en
-- cada app (tarjeta del plan de AduaniaX) y, al cerrar el mes de un contrato
-- manual, avisa del excedente y Vinqulia lo factura aparte
-- (factura_de_excedente). Para eso Auth tiene que saber cuántas horas se
-- usaron: el CRM, que es quien registra cada atención, se lo dice.
--
-- Reglas del dueño (2026-10-21):
--   * Se cuenta en horas completas: el total de minutos que consumen en el mes
--     se redondea hacia ARRIBA a la hora siguiente (1 h 10 min = 2 h).
--   * Cada registro (alta o corrección) reporta solo la diferencia contra lo
--     ya reportado de esa empresa, app y mes; una corrección puede restar.
--   * El CRM y Auth comparten base de datos: se llama directo a
--     kontrolia_auth.record_usage() con una llave por registro, así un
--     reintento nunca cuenta dos veces. Si Auth no está (otra instalación) o
--     falla, el registro de tiempo se guarda igual y el intento queda en la
--     bitácora con el error; el siguiente registro del mes pone al día la
--     diferencia.
--   * La app sale del contrato del ticket (crm.contracts.application_slug);
--     sin contrato no se reporta. La organización de Auth sale de la empresa
--     ligada (companies.source = 'kontrolia_auth', external_id).
--   * Solo el mes en curso de Auth (mes calendario UTC): un registro con
--     fecha de otro mes se guarda en el CRM pero no se reporta.
--
-- New tables:
--   crm.soporte_reportes_auth   bitácora de cada reporte a Auth (solo alta).
-- New functions:
--   crm.soporte_reportar_a_auth()   disparador AFTER INSERT en
--                                   crm.soporte_tiempos.
-- Security (RLS + policies):
--   soporte_reportes_auth: lectura para la organización (authenticated);
--   escribe solo el disparador (security definer). La función corre como su
--   dueño para poder llamar a record_usage(), que solo ejecuta service_role.
-- Activities and Permissions:
--   Sin permisos nuevos.

create table if not exists crm.soporte_reportes_auth (
    id bigint generated by default as identity primary key,
    organization_id uuid not null,
    tiempo_id bigint not null references crm.soporte_tiempos (id) on delete restrict,
    company_id bigint not null references crm.companies (id) on delete restrict,
    application_slug text,
    -- Primer día del mes que se reporta (mes del CRM = mes de Auth).
    mes date not null,
    minutos_del_mes integer not null,
    horas_del_mes integer not null,
    -- Horas que se mandaron a Auth en este reporte (puede ser negativa o 0).
    horas_reportadas integer not null,
    -- REPORTADO | SIN_CAMBIO | OMITIDO | ERROR
    estado text not null
        check (estado in ('REPORTADO', 'SIN_CAMBIO', 'OMITIDO', 'ERROR')),
    detalle text,
    created_at timestamp with time zone not null default now()
);

create index if not exists soporte_reportes_auth_mes_idx
    on crm.soporte_reportes_auth (company_id, application_slug, mes);
create index if not exists soporte_reportes_auth_tiempo_idx
    on crm.soporte_reportes_auth (tiempo_id);

alter table crm.soporte_reportes_auth enable row level security;
drop policy if exists "Support usage reports are scoped to the organization" on crm.soporte_reportes_auth;
create policy "Support usage reports are scoped to the organization" on crm.soporte_reportes_auth
    for select to authenticated using (organization_id = crm.current_organization_id());

revoke all on table crm.soporte_reportes_auth from anon;
revoke all on table crm.soporte_reportes_auth from authenticated;
grant select on table crm.soporte_reportes_auth to authenticated;
grant select, insert on table crm.soporte_reportes_auth to service_role;

create or replace function crm.soporte_reportar_a_auth() returns trigger
    language plpgsql
    security definer
    set search_path = ''
    as $$
declare
  empresa record;
  aplicacion text;
  org_auth uuid;
  app_auth uuid;
  mes_crm date := date_trunc('month', new.fecha_atencion)::date;
  mes_auth date;
  minutos integer;
  horas integer;
  ya integer;
  diferencia integer;
  anotar_estado text;
  anotar_detalle text;
begin
  -- Solo lo que consume horas (las fallas del sistema no se cuentan).
  if not new.consume then
    return null;
  end if;

  select c.source, c.external_id into empresa from crm.companies c where c.id = new.company_id;
  select ct.application_slug into aplicacion from crm.contracts ct where ct.id = new.contract_id;

  if to_regprocedure('kontrolia_auth.record_usage(uuid,uuid,text,integer,text)') is null then
    return null; -- instalación sin KontrolIA Auth en la misma base
  end if;

  -- Una empresa a la vez: dos registros simultáneos no reportan la misma
  -- diferencia.
  perform pg_advisory_xact_lock(hashtext('crm.soporte_reportar_a_auth'), new.company_id::integer);

  -- Minutos que consumen en el mes, de los tiempos de esta empresa ligados a
  -- un contrato de la misma app (correcciones incluidas).
  select coalesce(sum(t.minutos), 0)::integer into minutos
    from crm.soporte_tiempos t
    left join crm.contracts ct on ct.id = t.contract_id
   where t.company_id = new.company_id
     and t.consume
     and t.fecha_atencion >= mes_crm
     and t.fecha_atencion < (mes_crm + interval '1 month')::date
     and ct.application_slug is not distinct from aplicacion;
  horas := ceil(greatest(minutos, 0) / 60.0)::integer;

  select coalesce(sum(r.horas_reportadas), 0)::integer into ya
    from crm.soporte_reportes_auth r
   where r.company_id = new.company_id
     and r.application_slug is not distinct from aplicacion
     and r.mes = mes_crm
     and r.estado = 'REPORTADO';
  diferencia := horas - ya;

  if aplicacion is null then
    anotar_estado := 'OMITIDO';
    anotar_detalle := 'El ticket no tiene contrato: no se sabe a qué app reportar.';
  elsif empresa.source is distinct from 'kontrolia_auth' or empresa.external_id is null then
    anotar_estado := 'OMITIDO';
    anotar_detalle := 'La empresa no está ligada a una organización de KontrolIA Auth.';
  else
    mes_auth := kontrolia_auth.usage_period_start('month');
    select a.id into app_auth from kontrolia_auth.applications a where a.slug = aplicacion;
    begin
      org_auth := empresa.external_id::uuid;
    exception when others then
      org_auth := null;
    end;
    if app_auth is null or org_auth is null then
      anotar_estado := 'OMITIDO';
      anotar_detalle := format('No existe la app %s o la organización %s en KontrolIA Auth.', aplicacion, empresa.external_id);
    elsif mes_auth is distinct from mes_crm then
      anotar_estado := 'OMITIDO';
      anotar_detalle := format('La atención es de %s y Auth ya cuenta %s: no se reporta a otro mes.',
                               to_char(mes_crm, 'YYYY-MM'), to_char(mes_auth, 'YYYY-MM'));
    elsif diferencia = 0 then
      anotar_estado := 'SIN_CAMBIO';
    else
      begin
        perform kontrolia_auth.record_usage(org_auth, app_auth, 'soporte', diferencia,
                                            'crm-soporte-tiempo:' || new.id);
        anotar_estado := 'REPORTADO';
      exception when others then
        anotar_estado := 'ERROR';
        anotar_detalle := sqlerrm;
      end;
    end if;
  end if;

  insert into crm.soporte_reportes_auth (organization_id, tiempo_id, company_id, application_slug, mes,
                                         minutos_del_mes, horas_del_mes, horas_reportadas, estado, detalle)
  values (new.organization_id, new.id, new.company_id, aplicacion, mes_crm,
          minutos, horas, case when anotar_estado = 'REPORTADO' then diferencia else 0 end,
          anotar_estado, anotar_detalle);
  return null;
end;
$$;

revoke all on function crm.soporte_reportar_a_auth() from public;

drop trigger if exists soporte_tiempos_reportar_a_auth_trigger on crm.soporte_tiempos;
create trigger soporte_tiempos_reportar_a_auth_trigger
    after insert on crm.soporte_tiempos
    for each row execute function crm.soporte_reportar_a_auth();

-- ── Arranque: lo que ya se registró este mes ─────────────────────────────
-- Los tiempos guardados antes de este disparador se reportan una sola vez por
-- empresa y app (llave por empresa, app y mes), con el último registro como
-- referencia en la bitácora. Sin KontrolIA Auth en la base no hace nada.
do $$
declare
  g record;
  mes_auth date;
  org_auth uuid;
  app_auth uuid;
  horas integer;
  anotar_estado text;
  anotar_detalle text;
begin
  if to_regprocedure('kontrolia_auth.record_usage(uuid,uuid,text,integer,text)') is null then
    return;
  end if;
  mes_auth := kontrolia_auth.usage_period_start('month');
  for g in
    select t.organization_id, t.company_id, ct.application_slug, c.source, c.external_id,
           coalesce(sum(t.minutos), 0)::integer as minutos, max(t.id) as ultimo
      from crm.soporte_tiempos t
      join crm.companies c on c.id = t.company_id
      join crm.contracts ct on ct.id = t.contract_id
     where t.consume
       and date_trunc('month', t.fecha_atencion)::date = mes_auth
       and not exists (select 1 from crm.soporte_reportes_auth r
                        where r.company_id = t.company_id
                          and r.application_slug is not distinct from ct.application_slug
                          and r.mes = mes_auth)
     group by 1, 2, 3, 4, 5
  loop
    horas := ceil(greatest(g.minutos, 0) / 60.0)::integer;
    anotar_detalle := null;
    select a.id into app_auth from kontrolia_auth.applications a where a.slug = g.application_slug;
    org_auth := case when g.source = 'kontrolia_auth' then g.external_id::uuid end;
    if app_auth is null or org_auth is null then
      anotar_estado := 'OMITIDO';
      anotar_detalle := 'Sin app u organización en KontrolIA Auth.';
    elsif horas = 0 then
      anotar_estado := 'SIN_CAMBIO';
    else
      begin
        perform kontrolia_auth.record_usage(org_auth, app_auth, 'soporte', horas,
                                            format('crm-soporte-inicial:%s:%s:%s', g.company_id, g.application_slug, mes_auth));
        anotar_estado := 'REPORTADO';
      exception when others then
        anotar_estado := 'ERROR';
        anotar_detalle := sqlerrm;
      end;
    end if;
    insert into crm.soporte_reportes_auth (organization_id, tiempo_id, company_id, application_slug, mes,
                                           minutos_del_mes, horas_del_mes, horas_reportadas, estado, detalle)
    values (g.organization_id, g.ultimo, g.company_id, g.application_slug, mes_auth, g.minutos, horas,
            case when anotar_estado = 'REPORTADO' then horas else 0 end, anotar_estado, anotar_detalle);
  end loop;
end $$;
