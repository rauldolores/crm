-- Auditoría de las decisiones del modelo de clasificación.
--
-- Cada vez que el CRM actúa por su cuenta a partir de una decisión de Jev
-- —clasificar un ticket que entra solo, descartar un formulario como spam—
-- queda aquí la decisión, su confianza y si se aplicó o no. Sin esto,
-- ajustar los umbrales es adivinar: nadie sabría cuántas veces acertó, ni
-- qué se descartó, ni si subir el corte a 0.8 dejaría fuera trabajo real.
--
-- Es un registro de auditoría: se lee, no se edita. Escribe solo el
-- servidor con la clave de servicio; `authenticated` solo puede leer lo de
-- su organización (hay texto de clientes en `detalle`).
create table if not exists crm.ai_decisions (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    -- Qué se decidió: ticket_priority | ticket_category | form_spam |
    -- survey_topic | email_intent | duplicate_contact | duplicate_company |
    -- deal_loss_reason. Texto libre a propósito: cada caso nuevo no debería
    -- necesitar una migración.
    kind text not null,
    -- La opción elegida (preguntas de tipo choice) o "true"/"false" (noul).
    value text,
    -- De 0 a 1. En un noul es la probabilidad; en un choice, la confianza.
    confidence numeric(4, 3),
    -- Si el CRM actuó o se quedó mirando (por debajo del umbral).
    applied boolean not null default false,
    -- Modelo que respondió, para no comparar peras con manzanas cuando
    -- cambie de versión.
    model text,
    -- A qué fila se aplicó, cuando existe una: tickets, contacts…
    entity_table text,
    entity_id bigint,
    -- Lo mínimo para juzgar un falso positivo cuando NO hay fila que mirar:
    -- un formulario descartado por spam no deja rastro en ningún otro
    -- sitio, y sin una muestra del texto nadie puede revisar si se tiró
    -- trabajo de verdad. Recortado por la aplicación.
    detalle text,
    created_at timestamp with time zone not null default now()
);

create index if not exists ai_decisions_organization_idx
    on crm.ai_decisions (organization_id, created_at desc);
create index if not exists ai_decisions_kind_idx
    on crm.ai_decisions (organization_id, kind, created_at desc);
create index if not exists ai_decisions_entity_idx
    on crm.ai_decisions (entity_table, entity_id);

alter table crm.ai_decisions enable row level security;

-- Solo lectura, y solo de su organización. Escribe el servidor con la clave
-- de servicio: sin política de escritura, nadie puede falsear ni borrar una
-- constancia desde el navegador.
drop policy if exists "ai_decisions_select_own_org" on crm.ai_decisions;
create policy "ai_decisions_select_own_org" on crm.ai_decisions
    for select to authenticated
    using (organization_id = crm.current_organization_id());

grant select on table crm.ai_decisions to authenticated, service_role;
grant insert on table crm.ai_decisions to service_role;
grant usage, select on sequence crm.ai_decisions_id_seq to service_role;
