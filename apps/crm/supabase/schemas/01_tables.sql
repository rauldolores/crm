    contract_id bigint,
    quote_id bigint,
    ticket_id bigint,
    deal_id bigint,
    -- Para una oportunidad, el día en que entró en la etapa: así la regla
    -- actúa una vez por estancia, y vuelve a contar si sale y regresa.
    due_on date not null,
    created_at timestamp with time zone not null default now()
);
create unique index automation_runs_once_uk
    on crm.automation_runs (automation_id, contract_id, due_on);
create unique index automation_runs_quote_once_uk
    on crm.automation_runs (automation_id, quote_id);
create unique index automation_runs_deal_once_uk
    on crm.automation_runs (automation_id, deal_id, due_on);
create index automation_runs_ticket_idx
    on crm.automation_runs (automation_id, ticket_id);
create index automation_runs_organization_id_idx
    on crm.automation_runs (organization_id);

-- Auditoría de las decisiones del modelo de clasificación (TypeSafe Jev).
-- Cada vez que el CRM actúa por su cuenta a partir de una decisión suya
-- —clasificar un ticket que entra solo, descartar un formulario como spam—
-- queda aquí la decisión, su confianza y si se aplicó. Sin esto, ajustar los
-- umbrales es adivinar: nadie sabría cuántas veces acertó ni qué se descartó.
-- Registro de auditoría: se lee, no se edita. Escribe solo el servidor con la
-- clave de servicio.
create table crm.ai_decisions (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    -- ticket_priority | ticket_category | form_spam | survey_topic |
    -- email_intent | duplicate_contact | duplicate_company |
    -- deal_loss_reason. Texto libre a propósito: un caso nuevo no debería
    -- necesitar una migración.
    kind text not null,
    -- La opción elegida (preguntas de tipo choice) o "true"/"false" (noul).
    value text,
    -- De 0 a 1. En un noul es la probabilidad; en un choice, la confianza.
    confidence numeric(4, 3),
    -- Si el CRM actuó o se quedó mirando (por debajo del umbral).
    applied boolean not null default false,
    -- Modelo que respondió, para no comparar peras con manzanas cuando
    -- cambie de versión.
    model text,
    -- A qué fila se aplicó, cuando existe una: tickets, contacts…
    entity_table text,
    entity_id bigint,
    -- Lo mínimo para juzgar un falso positivo cuando NO hay fila que mirar:
    -- un formulario descartado por spam no deja rastro en ningún otro sitio.
    -- Recortado por la aplicación.
    detalle text,
    created_at timestamp with time zone not null default now()
);
create index ai_decisions_organization_idx
    on crm.ai_decisions (organization_id, created_at desc);
create index ai_decisions_kind_idx
    on crm.ai_decisions (organization_id, kind, created_at desc);
create index ai_decisions_entity_idx
    on crm.ai_decisions (entity_table, entity_id);

