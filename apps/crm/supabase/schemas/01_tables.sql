-- Contratos y suscripciones: la relación que DURA.
--
-- Se modela con periodos y no como "una compra que se repite" porque es lo
-- que permite lo que de verdad se pregunta: qué está activo hoy, qué vence el
-- mes que viene, qué se pausó y qué cambió de importe por el camino.
create table crm.contracts (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    company_id bigint not null,
    name text not null,
    -- active | paused | cancelled | expired
    status text not null default 'active',
    -- monthly | quarterly | yearly | one_time
    billing_period text,
    amount numeric,
    currency text not null default 'MXN',
    started_on date,
    -- Próxima renovación o vencimiento: es la fecha sobre la que se avisa.
    renews_on date,
    ended_on date,
    auto_renew boolean not null default true,
    -- De dónde salió: manual, faqturia, el ERP del cliente, una tienda…
    source text not null default 'manual',
    external_id text,
    notes text,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);

-- Compras: los HECHOS puntuales (una factura, un pedido, un cobro).
create table crm.purchases (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    company_id bigint not null,
    -- Si la compra corresponde a un contrato (una mensualidad, por ejemplo).
    contract_id bigint,
    -- Número visible en el sistema de origen (folio de factura, nº de pedido).
    reference text,
    purchased_on date not null default current_date,
    amount numeric not null default 0,
    currency text not null default 'MXN',
    -- paid | pending | cancelled | refunded
    status text not null default 'paid',
    source text not null default 'manual',
    external_id text,
    created_at timestamp with time zone not null default now()
);

-- Líneas de la compra: el QUÉ. `description` y `unit_price` son la foto del
