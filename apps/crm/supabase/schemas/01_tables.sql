create table crm.api_keys (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    name text not null,
    key_prefix text not null,
    key_hash text not null unique,
    active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    last_used_at timestamp with time zone
);

-- Servidor de correo saliente de la organización: por dónde salen TODOS los
-- correos que envía el CRM (envío manual desde una ficha, automatizaciones…).
--
-- Una fila por organización, de ahí la clave primaria: cada cliente envía
-- desde su propio dominio y con su propia cuenta del proveedor.
--
-- OJO con `api_key`: es un secreto reutilizable, no un hash como en
-- crm.api_keys —hay que presentarlo al proveedor en cada envío—, así que
-- esta tabla NO se expone. No tiene grants para anon/authenticated, no tiene
-- políticas RLS (nadie pasa salvo service_role), y está en la lista de
-- recursos prohibidos del puente /api/datos, que consulta con la clave de
-- servicio y sí llegaría a leerla. Se gestiona solo por /api/correos/configuracion,
-- que nunca devuelve el secreto.
-- Cola de correos que dejan encolados las automatizaciones. El disparador
-- solo encola porque armar el correo exige el diseño de plantillaBase.ts y
-- los campos de fusión de valoresDeFusion.ts, ambos en TypeScript: el
-- despachador (crm.despachar_correos) avisa a la aplicación, que es quien
-- renderiza y envía.
create table crm.email_outbox (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    automation_id bigint,
    template_id bigint not null,
    contact_id bigint not null,
    -- La oportunidad que originó el envío, si la regla venía de un deal:
    -- es lo que permite usar {{oportunidad.*}} en la plantilla.
    deal_id bigint,
    -- El contrato que originó el envío, si la regla era de renovación:
    -- es lo que permite usar {{contrato.*}} en la plantilla.
    contract_id bigint,
    attempts integer not null default 0,
    max_attempts integer not null default 5,
    next_attempt_at timestamp with time zone not null default now(),
    sent_at timestamp with time zone,
    last_error text,
    created_at timestamp with time zone not null default now()
);

create index email_outbox_pendientes_idx
    on crm.email_outbox (next_attempt_at)
    where sent_at is null;
create index email_outbox_organization_id_idx
    on crm.email_outbox (organization_id);

