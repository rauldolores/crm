-- Servidor de correo saliente de la organización: por dónde salen TODOS los
-- correos que envía el CRM (envío manual desde una ficha, automatizaciones…).
--
-- Una fila por organización, de ahí la clave primaria: cada cliente envía
-- desde su propio dominio y con su propia cuenta del proveedor.
--
-- OJO con `api_key`: es un secreto reutilizable, no un hash como en
-- crm.api_keys —hay que presentarlo al proveedor en cada envío—, así que
-- esta tabla NO se expone. No tiene grants para anon/authenticated, no tiene
-- políticas RLS (nadie pasa salvo service_role), y está en la lista de
-- recursos prohibidos del puente /api/datos, que consulta con la clave de
-- servicio y sí llegaría a leerla. Se gestiona solo por /api/correos/configuracion,
-- que nunca devuelve el secreto.
-- Cola de correos que dejan encolados las automatizaciones. El disparador
-- solo encola porque armar el correo exige el diseño de plantillaBase.ts y
-- los campos de fusión de valoresDeFusion.ts, ambos en TypeScript: el
-- despachador (crm.despachar_correos) avisa a la aplicación, que es quien
-- renderiza y envía.
create table crm.email_outbox (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    automation_id bigint,
    template_id bigint not null,
    contact_id bigint not null,
    -- La oportunidad que originó el envío, si la regla venía de un deal:
    -- es lo que permite usar {{oportunidad.*}} en la plantilla.
    deal_id bigint,
    -- El contrato que originó el envío, si la regla era de renovación:
    -- es lo que permite usar {{contrato.*}} en la plantilla.
    contract_id bigint,
    -- La cotización que originó el envío (recordatorio sin respuesta):
    -- es lo que permite usar {{cotizacion.*}} en la plantilla.
    quote_id bigint,
    -- El ticket que originó el envío: permite {{ticket.*}} en la plantilla.
    ticket_id bigint,
    attempts integer not null default 0,
    max_attempts integer not null default 5,
    next_attempt_at timestamp with time zone not null default now(),
    sent_at timestamp with time zone,
    last_error text,
    created_at timestamp with time zone not null default now(),
    -- La acción masiva que encoló este correo, si vino de una. Es lo que
    -- permite contar el avance sin una tabla de renglones aparte: el estado
    -- de cada envío ya vive aquí (sent_at, attempts, last_error).
    bulk_job_id bigint
);

create index email_outbox_pendientes_idx
    on crm.email_outbox (next_attempt_at)
    where sent_at is null;
create index email_outbox_organization_id_idx
    on crm.email_outbox (organization_id);
-- Para el avance de una acción masiva, que agrupa por este id.
create index email_outbox_bulk_job_idx
    on crm.email_outbox (bulk_job_id)
    where bulk_job_id is not null;

-- Una acción ejecutada sobre muchos registros a la vez: a qué se aplicó, qué
-- se pidió y qué se pudo encolar.
--
-- Guarda el encargo, NO el estado de cada envío: ese ya vive en la cola de
-- correo (sent_at, attempts, last_error) y duplicarlo en una tabla de
-- renglones daría dos verdades que se desincronizan. El avance se cuenta
-- agrupando crm.email_outbox por bulk_job_id.
--
-- Existe para tres cosas que una barra de progreso en el navegador no da:
-- cerrar el diálogo sin cancelar nada, volver a mirarlo mañana, y saber
-- quién lanzó un envío de cinco mil correos.
create table crm.bulk_jobs (
    organization_id uuid not null,
    id bigint generated by default as identity primary key,
    -- Quién la lanzó: una acción masiva es una decisión con nombre.
    sales_id bigint,
    -- Sobre qué recurso ('deals'). Texto y no enum: el catálogo de acciones
    -- masivas crecerá antes que una migración de tipo.
    resource text not null,
    -- Qué acción, con el mismo vocabulario que las automatizaciones
    -- ('send_email'), para que no haya dos catálogos que mantener.
    action_type text not null,
    action_params jsonb not null default '{}'::jsonb,
    -- Cómo se eligieron los registros, tal como se pidió: sirve para repetir
    -- la acción y para entender un encargo viejo.
    target jsonb not null default '{}'::jsonb,
    -- Cuántos registros caían en el encargo y cuántos se llegaron a encolar.
    -- La diferencia la explica `skipped_reasons`.
    requested integer not null default 0,
    enqueued integer not null default 0,
    -- Motivo -> cuántos. Lo valioso de un envío masivo no es el contador,
    -- es saber por qué 1.256 se quedaron fuera.
    skipped_reasons jsonb not null default '{}'::jsonb,
    created_at timestamp with time zone not null default now()
);

create index bulk_jobs_organization_id_idx
    on crm.bulk_jobs (organization_id, created_at desc);

-- Constancia de las automatizaciones por fecha ya disparadas: una regla no
