-- Afiliado: un contacto que llegó a la etapa de "afiliación completa" del
-- embudo configurado en el módulo Afiliados (ver crm.gestionar_modulo_afiliados
-- en 02_functions.sql). El módulo entero puede estar apagado por organización
-- sin que esta tabla deje de existir — solo deja de recibir filas nuevas.
create table crm.affiliates (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    company_id bigint not null,
    -- Oportunidad ganada que originó la afiliación. Puede quedar sin dueño si
    -- el deal se borra; el afiliado en sí no depende de que siga existiendo.
    deal_id bigint,
    -- El {id} de la URL de referidos (config.modules.affiliates.urlTemplate).
    -- Formato de slug: minúsculas, dígitos y guiones, sin empezar ni terminar
    -- en guión, para que sea válido en una URL sin escaparlo.
    referral_code text not null
        check (referral_code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    commission_percentage numeric,
    active boolean not null default true,
    -- Vínculo manual: el administrador lo rellena después de crear la cuenta
    -- en KontrolIA Auth. Mientras esté vacío, este contacto es afiliado pero
    -- nadie puede iniciar sesión "como" él.
    kontrolia_auth_user_id uuid,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);

create unique index affiliates_organization_contact_uk
    on crm.affiliates (organization_id, contact_id);
create unique index affiliates_organization_referral_code_uk
    on crm.affiliates (organization_id, referral_code);
create index affiliates_organization_id_idx on crm.affiliates (organization_id);
create index affiliates_kontrolia_auth_user_id_idx
    on crm.affiliates (kontrolia_auth_user_id);

