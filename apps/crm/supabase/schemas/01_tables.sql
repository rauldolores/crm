create table crm.webhooks (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    url text not null,
    -- Secreto de firma (X-Vinqulia-Firma = HMAC-SHA256 hex del cuerpo).
    secret text not null default encode(extensions.gen_random_bytes(24), 'hex'),
    -- Tablas suscritas; vacío = todas las notificables.
    resources text[] not null default '{}',
    -- Eventos concretos (contacts.created, deals.updated…); vacío = todos los
    -- del recurso. Es lo que permite integraciones bidireccionales sin bucle:
    -- un sistema que responde a «created» escribiendo en la ficha se suscribe
    -- solo a «created», así su propia escritura no le vuelve como «updated».
    events text[] not null default '{}',
    active boolean not null default true,
    created_at timestamp with time zone not null default now()
);

create index webhooks_organization_id_idx on crm.webhooks (organization_id);

-- Cola de envíos. El disparador solo encola —barato y dentro de la misma
-- transacción que el cambio— y el despachador programado envía y reintenta.
-- Antes el disparador hacía el POST en el momento y se tragaba los errores:
-- un receptor caído significaba un aviso perdido para siempre.
create table crm.webhook_deliveries (
    organization_id uuid not null default (auth.jwt() ->> 'organization_id')::uuid,
    id bigint generated by default as identity primary key,
    webhook_id bigint not null,
    -- Viaja en X-Vinqulia-Evento-Id para que el receptor pueda descartar
    -- duplicados por su cuenta.
    event_id uuid not null default extensions.gen_random_uuid(),
    event text not null,
    resource text not null,
    payload jsonb not null,
    attempts integer not null default 0,
    max_attempts integer not null default 5,
    next_attempt_at timestamp with time zone not null default now(),
    delivered_at timestamp with time zone,
    -- Identificador en pg_net mientras la petición está en vuelo; se limpia
    -- al reconciliar la respuesta.
    net_request_id bigint,
    last_status_code integer,
    last_error text,
    created_at timestamp with time zone not null default now()
);

create index webhook_deliveries_pendientes_idx
    on crm.webhook_deliveries (next_attempt_at)
    where delivered_at is null;
create index webhook_deliveries_en_vuelo_idx
    on crm.webhook_deliveries (net_request_id)
    where net_request_id is not null;
create index webhook_deliveries_organization_id_idx
    on crm.webhook_deliveries (organization_id);

